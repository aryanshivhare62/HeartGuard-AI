# -*- coding: utf-8 -*-
"""
run_eda.py
Automated Exploratory Data Analysis for HeartGuard AI Week 2.
Generates:
  - reports/EXPLORATORY_DATA_ANALYSIS_REPORT.md
  - reports/MISSINGNESS_REPORT.md
  - reports/DATASET_COMPATIBILITY_REPORT.md
All files written with UTF-8 encoding, ASCII-only content.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

BASE_DIR = Path(__file__).resolve().parents[1]
RAW_DIR = BASE_DIR / "data" / "raw"
REPORTS_DIR = BASE_DIR / "reports"
REPORTS_DIR.mkdir(parents=True, exist_ok=True)

# ------------------------------------------------------------------
# Column definitions
# ------------------------------------------------------------------
UCI_COLS = [
    "age", "sex", "cp", "trestbps", "chol", "fbs",
    "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal", "num",
]

NUMERIC_FEATURES = ["age", "trestbps", "chol", "thalach", "oldpeak"]
CATEGORICAL_FEATURES = ["cp", "restecg", "slope", "ca", "thal"]
BINARY_FEATURES = ["sex", "fbs", "exang"]
TARGET = "num"

STATLOG_COLS = [
    "age", "sex", "cp", "trestbps", "chol", "fbs",
    "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal", "target",
]

# ------------------------------------------------------------------
# Load datasets
# ------------------------------------------------------------------
def load_uci(name: str) -> pd.DataFrame:
    path = RAW_DIR / "uci" / f"{name}.data"
    df = pd.read_csv(path, header=None, names=UCI_COLS, na_values="?")
    df["site"] = name
    # Binarise target: 0 = no disease, 1 = disease (num >= 1)
    df["binary_target"] = (df["num"] >= 1).astype(float)
    df.loc[df["num"].isna(), "binary_target"] = np.nan
    return df


datasets = {
    "cleveland":   load_uci("cleveland"),
    "hungary":     load_uci("hungary"),
    "switzerland": load_uci("switzerland"),
    "va":          load_uci("va"),
}

statlog_raw = pd.read_csv(
    RAW_DIR / "statlog" / "heart.dat",
    sep=r"\s+", header=None,
    names=["age","sex","chestpain","restbp","chol","fbs",
           "restecg","maxhr","exang","oldpeak","slope","ca","thal","target"]
)
statlog_raw = statlog_raw.rename(columns={
    "chestpain": "cp", "restbp": "trestbps", "maxhr": "thalach"
})
statlog_raw["site"] = "statlog"
# Statlog target: 1=absence, 2=presence -> binary 0/1
statlog_raw["binary_target"] = (statlog_raw["target"] == 2).astype(int)
datasets["statlog"] = statlog_raw

print("Datasets loaded:")
for name, df in datasets.items():
    print(f"  {name}: {df.shape}")

# ------------------------------------------------------------------
# Helper: summary stats table string
# ------------------------------------------------------------------
def stats_table(df: pd.DataFrame, features: list) -> str:
    lines = []
    lines.append("| Feature | N | Mean | Median | Std | Min | Max | Skew | Missing |")
    lines.append("|---------|---|------|--------|-----|-----|-----|------|---------|")
    for col in features:
        if col not in df.columns:
            continue
        s = df[col].dropna()
        n = len(s)
        missing = df[col].isna().sum()
        if n == 0:
            lines.append(f"| {col} | 0 | - | - | - | - | - | - | {missing} |")
            continue
        lines.append(
            f"| {col} | {n} | {s.mean():.2f} | {s.median():.2f} | "
            f"{s.std():.2f} | {s.min():.2f} | {s.max():.2f} | "
            f"{s.skew():.2f} | {missing} |"
        )
    return "\n".join(lines)


def zero_count_table(df: pd.DataFrame, features: list) -> str:
    lines = []
    lines.append("| Feature | Zero count | Zero % |")
    lines.append("|---------|------------|--------|")
    for col in features:
        if col not in df.columns:
            continue
        n_zero = (df[col] == 0).sum()
        pct = 100.0 * n_zero / len(df) if len(df) > 0 else 0.0
        lines.append(f"| {col} | {n_zero} | {pct:.1f}% |")
    return "\n".join(lines)


def target_dist_table(df: pd.DataFrame) -> str:
    if "binary_target" not in df.columns:
        return "N/A"
    vc = df["binary_target"].value_counts(dropna=False).sort_index()
    total = len(df)
    lines = ["| Class | Count | Percent |", "|-------|-------|---------|"]
    for cls, cnt in vc.items():
        label = "No disease (0)" if cls == 0 else ("Disease (1)" if cls == 1 else "NaN")
        lines.append(f"| {label} | {cnt} | {100*cnt/total:.1f}% |")
    return "\n".join(lines)


# ------------------------------------------------------------------
# Build EDA Report
# ------------------------------------------------------------------
eda_path = REPORTS_DIR / "EXPLORATORY_DATA_ANALYSIS_REPORT.md"
with open(eda_path, "w", encoding="utf-8") as f:
    f.write("# Exploratory Data Analysis Report\n\n")
    f.write("> HeartGuard AI - Week 2 | Generated by scripts/run_eda.py\n\n")
    f.write("## 1. Dataset Overview\n\n")
    f.write("| Dataset | Rows | Columns | Missing cells | Missing % |\n")
    f.write("|---------|------|---------|---------------|-----------|\n")
    for name, df in datasets.items():
        total_cells = df.shape[0] * df.shape[1]
        missing = df.isna().sum().sum()
        pct = 100.0 * missing / total_cells if total_cells > 0 else 0.0
        f.write(f"| {name} | {df.shape[0]} | {df.shape[1]} | {missing} | {pct:.1f}% |\n")
    f.write("\n")

    f.write("## 2. Target (Diagnosis) Distribution by Site\n\n")
    for name, df in datasets.items():
        f.write(f"### {name.capitalize()}\n\n")
        f.write(target_dist_table(df) + "\n\n")

    f.write("## 3. Feature-level Statistics (Numeric Features)\n\n")
    for name, df in datasets.items():
        f.write(f"### {name.capitalize()}\n\n")
        f.write(stats_table(df, NUMERIC_FEATURES) + "\n\n")

    f.write("## 4. Missing Value Summary\n\n")
    f.write("| Dataset | Feature | Missing count | Missing % |\n")
    f.write("|---------|---------|---------------|-----------|\n")
    for name, df in datasets.items():
        for col in UCI_COLS:
            if col == "site":
                continue
            if col not in df.columns:
                continue
            n_miss = df[col].isna().sum()
            if n_miss > 0:
                pct = 100.0 * n_miss / len(df)
                f.write(f"| {name} | {col} | {n_miss} | {pct:.1f}% |\n")
    f.write("\n")

    f.write("## 5. Zero-coded Values (Potential Clinical Missingness)\n\n")
    f.write("Zero values in continuous clinical features may indicate missing data "
            "recorded as zero rather than NaN. The cause of zero coding is not verified "
            "from dataset documentation alone.\n\n")
    for name, df in datasets.items():
        f.write(f"### {name.capitalize()}\n\n")
        f.write(zero_count_table(df, NUMERIC_FEATURES) + "\n\n")

    f.write("## 6. Categorical Feature Distributions\n\n")
    for name, df in datasets.items():
        f.write(f"### {name.capitalize()}\n\n")
        for col in CATEGORICAL_FEATURES + BINARY_FEATURES:
            if col not in df.columns:
                continue
            vc = df[col].value_counts(dropna=False).sort_index()
            f.write(f"**{col}**\n\n")
            f.write("| Value | Count | % |\n")
            f.write("|-------|-------|---|\n")
            for val, cnt in vc.items():
                f.write(f"| {val} | {cnt} | {100*cnt/len(df):.1f}% |\n")
            f.write("\n")

    f.write("## 7. Correlation Analysis (Numeric Features vs Binary Target)\n\n")
    for name, df in datasets.items():
        f.write(f"### {name.capitalize()}\n\n")
        corr_features = NUMERIC_FEATURES + ["binary_target"]
        available = [c for c in corr_features if c in df.columns]
        numeric_df = df[available].apply(pd.to_numeric, errors="coerce")
        corr = numeric_df.corr()
        f.write("Pearson correlation matrix (numeric features + binary target):\n\n")
        header = "| Feature | " + " | ".join(available) + " |"
        separator = "|---------|" + "|".join(["-------"] * len(available)) + "|"
        f.write(header + "\n" + separator + "\n")
        for row_feat in available:
            row = f"| {row_feat} |"
            for col_feat in available:
                val = corr.loc[row_feat, col_feat]
                row += f" {val:.2f} |"
            f.write(row + "\n")
        f.write("\n")

    f.write("## 8. Class Imbalance Summary\n\n")
    f.write("| Dataset | N (no disease) | N (disease) | Imbalance ratio |\n")
    f.write("|---------|----------------|-------------|----------------|\n")
    for name, df in datasets.items():
        if "binary_target" not in df.columns:
            continue
        n0 = (df["binary_target"] == 0).sum()
        n1 = (df["binary_target"] == 1).sum()
        ratio = n0 / n1 if n1 > 0 else float("inf")
        f.write(f"| {name} | {n0} | {n1} | {ratio:.2f}:1 |\n")
    f.write("\n")

print(f"EDA report written to: {eda_path}")

# ------------------------------------------------------------------
# Build Missingness Report
# ------------------------------------------------------------------
miss_path = REPORTS_DIR / "MISSINGNESS_REPORT.md"
with open(miss_path, "w", encoding="utf-8") as f:
    f.write("# Missingness Report\n\n")
    f.write("> HeartGuard AI - Week 2 | Generated by scripts/run_eda.py\n\n")
    f.write("## Missing Values per Feature per Site\n\n")
    f.write("| Site | Feature | N missing | % missing | Notes |\n")
    f.write("|------|---------|-----------|-----------|-------|\n")

    notes_map = {
        "ca": "Number of major vessels coloured by fluoroscopy; often missing in external sites",
        "thal": "Thalassemia type; often missing in external sites",
        "slope": "ST slope; higher missingness in Hungary and VA",
        "chol": "Serum cholesterol; zero values in Switzerland/VA may reflect unrecorded values",
    }

    for name, df in datasets.items():
        for col in UCI_COLS:
            if col in ("site", "num"):
                continue
            if col not in df.columns:
                continue
            n_miss = df[col].isna().sum()
            pct = 100.0 * n_miss / len(df) if len(df) > 0 else 0.0
            note = notes_map.get(col, "")
            f.write(f"| {name} | {col} | {n_miss} | {pct:.1f}% | {note} |\n")

    f.write("\n## Notes\n\n")
    f.write("- Missing values in the UCI processed files are encoded as '?' in the original "
            "data and read as NaN here.\n")
    f.write("- Zero values in `chol`, `trestbps`, and `thalach` are distinct from NaN. "
            "Their clinical interpretation depends on site-specific data collection procedures "
            "which are not fully documented in the UCI repository. Cause of zero coding is "
            "NOT verified.\n")
    f.write("- Statlog (`heart.dat`) has no missing values per its UCI documentation.\n")

print(f"Missingness report written to: {miss_path}")

# ------------------------------------------------------------------
# Build Dataset Compatibility Report
# ------------------------------------------------------------------
compat_path = REPORTS_DIR / "DATASET_COMPATIBILITY_REPORT.md"
with open(compat_path, "w", encoding="utf-8") as f:
    f.write("# Dataset Compatibility Report\n\n")
    f.write("> HeartGuard AI - Week 2 | Generated by scripts/run_eda.py\n\n")

    f.write("## Overview\n\n")
    f.write("This report documents feature availability, target definitions, and "
            "population characteristics across UCI Heart Disease sites for cross-dataset "
            "generalisation experiments.\n\n")

    f.write("## Feature Availability\n\n")
    f.write("| Feature | Cleveland | Hungary | Switzerland | VA | Statlog |\n")
    f.write("|---------|-----------|---------|-------------|----|---------|\n")
    feature_list = [c for c in UCI_COLS if c not in ("num", "site")]
    for feat in feature_list:
        row = f"| {feat} |"
        for name in ["cleveland", "hungary", "switzerland", "va", "statlog"]:
            df = datasets[name]
            if feat not in df.columns:
                row += " N/A |"
                continue
            n_miss = df[feat].isna().sum()
            n_total = len(df)
            avail_pct = 100.0 * (n_total - n_miss) / n_total
            row += f" {avail_pct:.0f}% ({n_total - n_miss}/{n_total}) |"
        f.write(row + "\n")
    f.write("\n")

    f.write("## Target Variable Definitions\n\n")
    f.write("| Site | Raw target | Range | Binary mapping |\n")
    f.write("|------|------------|-------|---------------|\n")
    f.write("| Cleveland | num | 0-4 | 0 = no disease, 1 = disease (num>=1) |\n")
    f.write("| Hungary | num | 0-4 | 0 = no disease, 1 = disease (num>=1) |\n")
    f.write("| Switzerland | num | 0-4 | 0 = no disease, 1 = disease (num>=1) |\n")
    f.write("| VA Long Beach | num | 0-4 | 0 = no disease, 1 = disease (num>=1) |\n")
    f.write("| Statlog | target | 1-2 | 1=absence -> 0, 2=presence -> 1 |\n\n")

    f.write("## Population Demographics by Site\n\n")
    f.write("| Site | N | Age mean (SD) | Sex (% male) | Disease prevalence |\n")
    f.write("|------|---|---------------|--------------|-------------------|\n")
    for name, df in datasets.items():
        if name == "statlog":
            continue
        n = len(df)
        age_mean = df["age"].mean()
        age_std = df["age"].std()
        pct_male = 100.0 * (df["sex"] == 1).sum() / n
        prev = 100.0 * (df["binary_target"] == 1).sum() / n
        f.write(f"| {name} | {n} | {age_mean:.1f} ({age_std:.1f}) | {pct_male:.1f}% | {prev:.1f}% |\n")
    f.write("\n")

    f.write("## Feature Configuration Summary\n\n")
    f.write("Three feature configurations are defined for Pipeline A experiments:\n\n")
    f.write("| Configuration | Features (N) | Notes |\n")
    f.write("|---------------|-------------|-------|\n")
    f.write("| Full Diagnostic Set (13F) | 13 | All standard UCI features; missing `ca`/`thal` limits generalisability |\n")
    f.write("| Common Reduced Set - 10F | 10 | Includes cholesterol; better coverage across sites |\n")
    f.write("| Common Reduced Set - 9F  |  9 | Excludes cholesterol; best availability across all sites |\n\n")

    f.write("## Caveats and Limitations\n\n")
    f.write("1. Feature semantics may differ across sites despite sharing column names. "
            "Clinical validation of coding consistency is pending.\n")
    f.write("2. External site datasets (Hungary, Switzerland, VA) are used for "
            "zero-shot evaluation only. They must not influence model training, "
            "hyperparameter tuning, or threshold selection.\n")
    f.write("3. Switzerland has a high proportion of zero values in `chol`. "
            "The cause of this is not documented in the UCI dataset description "
            "and should not be attributed to specific clinical procedures without evidence.\n")
    f.write("4. Disease prevalence and demographic distributions vary substantially "
            "across sites, reflecting genuine population differences.\n")

print(f"Compatibility report written to: {compat_path}")
print("\nEDA complete.")

