# -*- coding: utf-8 -*-
"""
verify_statlog_duplicates.py
Programmatically compare Statlog heart.dat against Cleveland processed.cleveland.data.
Reports exact matches, near matches, and unmatched records.
No assumptions about duplicate identity are made.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.spatial.distance import cdist

BASE_DIR = Path(__file__).resolve().parents[1]
RAW_DIR = BASE_DIR / "data" / "raw"
REPORTS_DIR = BASE_DIR / "reports"
REPORTS_DIR.mkdir(parents=True, exist_ok=True)

# ------------------------------------------------------------------
# Column definitions
# ------------------------------------------------------------------
CLEVELAND_COLS = [
    "age", "sex", "cp", "trestbps", "chol", "fbs",
    "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal", "num",
]

STATLOG_COLS = [
    "age", "sex", "chestpain", "restbp", "chol", "fbs",
    "restecg", "maxhr", "exang", "oldpeak", "slope", "ca", "thal", "target",
]

# Features shared across both datasets after renaming
COMMON_FEATURES = [
    "age", "sex", "cp", "trestbps", "chol", "fbs",
    "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal",
]

# ------------------------------------------------------------------
# Load datasets
# ------------------------------------------------------------------
cleveland_path = RAW_DIR / "uci" / "cleveland.data"
statlog_path = RAW_DIR / "statlog" / "heart.dat"

cleveland = pd.read_csv(
    cleveland_path, header=None, names=CLEVELAND_COLS, na_values="?"
)

statlog_raw = pd.read_csv(
    statlog_path, sep=r"\s+", header=None, names=STATLOG_COLS
)

# Rename Statlog columns to match Cleveland naming convention
statlog = statlog_raw.rename(columns={
    "chestpain": "cp",
    "restbp": "trestbps",
    "maxhr": "thalach",
    "target": "num",
})

print(f"Cleveland rows: {len(cleveland)}, columns: {len(cleveland.columns)}")
print(f"Statlog rows:   {len(statlog)},   columns: {len(statlog.columns)}")

# ------------------------------------------------------------------
# Exact match via row hash (string representation of common features)
# NaN values in Cleveland have no counterpart in Statlog (Statlog has no missing values)
# ------------------------------------------------------------------
def row_key(row, features):
    parts = []
    for col in features:
        val = row.get(col, float("nan"))
        if pd.isna(val):
            parts.append("NA")
        else:
            parts.append(str(val))
    return "|".join(parts)


cleveland["_key"] = cleveland.apply(lambda r: row_key(r, COMMON_FEATURES), axis=1)
statlog["_key"] = statlog.apply(lambda r: row_key(r, COMMON_FEATURES), axis=1)

statlog_keys = set(statlog["_key"])
exact_match_mask = cleveland["_key"].isin(statlog_keys)
n_exact = exact_match_mask.sum()

# ------------------------------------------------------------------
# Near-match via Euclidean distance on numeric common features
# We fill NaN with -9999 (sentinel) so NaN rows cannot accidentally match
# ------------------------------------------------------------------
cle_num = cleveland[COMMON_FEATURES].apply(pd.to_numeric, errors="coerce").fillna(-9999).values
stat_num = statlog[COMMON_FEATURES].apply(pd.to_numeric, errors="coerce").fillna(-9999).values

NEAR_THRESHOLD = 1.0  # Euclidean distance threshold

D = cdist(cle_num, stat_num, metric="euclidean")

# Exclude exact matches (distance == 0) from near-match category
near_mask_i, near_mask_j = np.where((D > 0) & (D <= NEAR_THRESHOLD))
near_matches = [
    {
        "cleveland_index": int(i),
        "statlog_index": int(j),
        "distance": float(D[i, j]),
    }
    for i, j in zip(near_mask_i, near_mask_j)
]

# ------------------------------------------------------------------
# Counts
# ------------------------------------------------------------------
n_cle = len(cleveland)
n_stat = len(statlog)
n_near = len(near_matches)

# Statlog rows with distance == 0 to any Cleveland row
exact_stat_indices = set()
for i, j in zip(*np.where(D == 0)):
    exact_stat_indices.add(j)
n_exact_stat = len(exact_stat_indices)

n_unmatched_cle = n_cle - n_exact
n_unmatched_stat = n_stat - n_exact_stat

# ------------------------------------------------------------------
# Write report (UTF-8, ASCII-only content)
# ------------------------------------------------------------------
report_path = REPORTS_DIR / "STATLOG_DUPLICATE_REPORT.md"
with open(report_path, "w", encoding="utf-8") as f:
    f.write("# Statlog vs. Cleveland Duplicate Verification Report\n\n")
    f.write("> Generated by scripts/verify_statlog_duplicates.py\n\n")
    f.write("## Dataset Summary\n\n")
    f.write("| Dataset   | Rows | Features used for comparison |\n")
    f.write("|-----------|------|-----------------------------|\n")
    f.write(f"| Cleveland | {n_cle}  | 13 (common features, NaNs coded as NA) |\n")
    f.write(f"| Statlog   | {n_stat}  | 13 (common features, no missing values)  |\n\n")

    f.write("## Exact Matches (string-key comparison on 13 common features)\n\n")
    f.write(f"- Cleveland rows with an exact Statlog counterpart: **{n_exact}** of {n_cle}\n")
    f.write(f"- Statlog rows with an exact Cleveland counterpart: **{n_exact_stat}** of {n_stat}\n\n")

    f.write("## Near Matches (Euclidean distance > 0 and <= 1.0 on 13 features)\n\n")
    f.write(f"Near-match pairs found: **{n_near}**\n\n")
    if near_matches:
        f.write("| Cleveland index | Statlog index | Distance |\n")
        f.write("|-----------------|---------------|----------|\n")
        for nm in near_matches[:20]:
            f.write(f"| {nm['cleveland_index']} | {nm['statlog_index']} | {nm['distance']:.4f} |\n")
        if n_near > 20:
            f.write(f"| ... | ... | ({n_near - 20} more rows omitted) |\n")
        f.write("\n")
    else:
        f.write("No near-match pairs found.\n\n")

    f.write("## Unmatched Records\n\n")
    f.write(f"- Cleveland rows with no exact or near match in Statlog: **{n_unmatched_cle}**\n")
    f.write(f"- Statlog rows with no exact or near match in Cleveland: **{n_unmatched_stat}**\n\n")

    f.write("## Notes and Limitations\n\n")
    f.write("1. Exact matching uses string representation of all 13 common features. "
            "Cleveland missing values (coded '?') are represented as 'NA'; Statlog has "
            "no missing values, so Cleveland-NaN rows cannot match any Statlog row exactly.\n")
    f.write("2. Near matching uses Euclidean distance on numeric values. "
            "Cleveland rows containing NaN are assigned a sentinel value of -9999 so they "
            "cannot accidentally appear as near matches.\n")
    f.write("3. Statlog and Cleveland use the same coding for most features, but the "
            "target variable differs: Cleveland 'num' ranges 0-4; Statlog 'target' is "
            "binary (1=absence, 2=presence). Target values are excluded from matching.\n")
    f.write("4. **Conclusion: Statlog/Cleveland exact duplicate status remains UNVERIFIED** "
            "pending clinical review of feature coding differences. This script reports "
            "only programmatic string and numeric similarity.\n")

print(f"\nReport written to: {report_path}")
print(f"Exact matches (Cleveland->Statlog): {n_exact}/{n_cle}")
print(f"Near matches (dist <= {NEAR_THRESHOLD}): {n_near}")
print(f"Unmatched Cleveland rows: {n_unmatched_cle}")
print(f"Unmatched Statlog rows:   {n_unmatched_stat}")
